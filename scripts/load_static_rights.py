def supabase_headers():
    return {
        "apikey": SUPABASE_SERVICE_KEY,
        "Authorization": f"Bearer {SUPABASE_SERVICE_KEY}",
        "Content-Type": "application/json",
    }


def url_already_exists(source_url: str) -> bool:
    endpoint = f"{SUPABASE_URL}/rest/v1/{TABLE_NAME}"
    params = {"source_url": f"eq.{source_url}", "select": "id"}
    resp = requests.get(endpoint, headers=supabase_headers(), params=params, timeout=REQUEST_TIMEOUT)
    resp.raise_for_status()
    return len(resp.json()) > 0


def insert_row(row: dict):
    endpoint = f"{SUPABASE_URL}/rest/v1/{TABLE_NAME}"
    headers = supabase_headers()
    headers["Prefer"] = "return=representation"

    payload = dict(row)
    payload.setdefault("verified", False)
    payload.setdefault("review_status", "suggest_verify")
    payload.setdefault("review_reason", "תוכן נחקר ונכתב ידנית (לא ע\"י AI), מומלץ לאמת מול המקור בכל זאת")

    resp = requests.post(endpoint, headers=headers, json=payload, timeout=REQUEST_TIMEOUT)
    if resp.status_code >= 300:
        raise RuntimeError(f"שגיאת הכנסה לדאטהבייס ({resp.status_code}): {resp.text}")
    return resp.json()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true", help="רק להציג מה היה נכנס, בלי לכתוב לדאטהבייס")
    args = parser.parse_args()

    if not args.dry_run:
        missing = [name for name, val in [("SUPABASE_URL", SUPABASE_URL), ("SUPABASE_SERVICE_KEY", SUPABASE_SERVICE_KEY)] if not val]
        if missing:
            print(f"חסרים משתני סביבה: {', '.join(missing)}")
            sys.exit(1)

    print(f"סה״כ {len(ROWS)} שורות להכנסה.\n")
    inserted, skipped, failed = 0, 0, 0

    for i, row in enumerate(ROWS, 1):
        url = row["source_url"]
        print(f"[{i}/{len(ROWS)}] {row['title_he']}")
        try:
            if not args.dry_run and url_already_exists(url):
                print("   -> כבר קיים בדאטהבייס, מדלג.\n")
                skipped += 1
                continue

            if args.dry_run:
                print(f"   קטגוריה: {row['category']} | city_id: {row['city_id']} | תגיות: {row['tags']}")
                print("   [DRY RUN] לא נכנס בפועל לדאטהבייס.\n")
            else:
                insert_row(row)
                print("   -> נכנס בהצלחה לדאטהבייס.\n")
                inserted += 1

        except Exception as e:
            print(f"   !! שגיאה: {e}\n")
            failed += 1

        time.sleep(REQUEST_DELAY_SECONDS)

    print("=" * 50)
    print(f"סיכום: נכנסו {inserted} | דולגו (כפילות) {skipped} | נכשלו {failed}")


if __name__ == "__main__":
    main()